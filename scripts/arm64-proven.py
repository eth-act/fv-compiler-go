#!/usr/bin/env python3
"""The proven-only `ARM64.rules` rule set (issue #385).

  scripts/arm64-proven.py      # rewrite GoFV/Rules/ProvenARM64.lean and
                               # GoFV/Proof/Low/ProvenARM64.lean from the
                               # `r_ARM64_*_sound` theorems of GoFV/Proof/Low/Rules/*.lean

A value rule is proven by a theorem `r_ARM64_<n>_sound : ArmRule.Checked r_ARM64_<n>`, a block
rule by `r_ARM64_<n>_sound : BlockRuleL.Sound r_ARM64_<n>`. The rule set keeps the generated
matching order (`GoFV.Rules.Generated.ARM64.ruleSet`: ops by Go name, rules per op as rulegen
tries them; block kinds likewise) restricted to the proven rules.
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
GEN = ROOT / "GoFV/Rules/Generated/ARM64.lean"
GEN_DIR = ROOT / "GoFV/Rules/Generated/ARM64"
LEMMAS = ROOT / "GoFV/Proof/Low/Rules"
OUT_SET = ROOT / "GoFV/Rules/ProvenARM64.lean"
OUT_PROOF = ROOT / "GoFV/Proof/Low/ProvenARM64.lean"


def proven():
    vals, blocks, mods = set(), set(), []
    pat = re.compile(r"^theorem (r_ARM64_\w+)_sound : (ArmRule\.Checked|BlockRuleL\.Sound) ", re.M)
    for f in sorted(LEMMAS.glob("*.lean")):
        found = pat.findall(f.read_text())
        if found:
            mods.append("GoFV.Proof.Low.Rules." + f.stem)
        for name, kind in found:
            (vals if kind == "ArmRule.Checked" else blocks).add(name)
    return vals, blocks, mods


def lists(kind):
    """`ops_X`/`blocks_K` definitions of the generated modules: name -> rule names."""
    out = {}
    pat = re.compile(r"^def (%s_\w+) : List \w+ := \[(.*)\]$" % kind, re.M)
    for f in sorted(GEN_DIR.glob("*.lean")):
        for name, body in pat.findall(f.read_text()):
            out[name] = [x.strip() for x in body.split(",") if x.strip()]
    return out


def order():
    text = GEN.read_text()
    vals = re.findall(r"\(\.(\w+), (ops_\w+)\)", text)
    blocks = re.findall(r"\(\.(\w+), (blocks_\w+)\)", text)
    return vals, blocks


def main():
    pv, pb, mods = proven()
    ops, bls = lists("ops"), lists("blocks")
    vord, bord = order()
    values = [(op, [r for r in ops[l] if r in pv]) for op, l in vord]
    values = [(op, rs) for op, rs in values if rs]
    blocks = [(k, [r for r in bls[l] if r in pb]) for k, l in bord]
    blocks = [(k, rs) for k, rs in blocks if rs]
    nv = sum(len(rs) for _, rs in values)
    nb = sum(len(rs) for _, rs in blocks)
    q = "Generated.ARM64."

    def entries(xs):
        if not xs:
            return "[]"
        return "[" + ",\n    ".join(
            "(.%s, [%s])" % (k, ", ".join(q + r for r in rs)) for k, rs in xs) + "]"

    OUT_SET.write_text(f"""-- Generated by scripts/arm64-proven.py from the `r_ARM64_*_sound` theorems of GoFV/Proof/Low/Rules. Do not edit.
import GoFV.Rules.Generated.ARM64

/-!
# The proven-only `ARM64.rules` rule set (issue #385)

`ARM64.rules` restricted to the rules with a merged lowered obligation (`ArmRule.Sound`,
`ArmRule.SetOp`, `ArmRule.Rename`, `BlockRuleL.Sound`; `GoFV/Proof/Low/ProvenARM64.lean`), in
matching order: the rule set of the checked `lower` (`GoFV.Opt.lowerChecked`).
-/

namespace GoFV.Rules.ProvenARM64

open GoFV.Rules

/-- `ARM64.rules` restricted to its {nv} proven value rules and {nb} proven block rules. -/
def lower : RuleSet where
  name := "ARM64"
  values := {entries(values)}
  blocks := {entries(blocks)}

end GoFV.Rules.ProvenARM64
""")

    def proofs(xs):
        if not xs:
            return "exact trivial"
        return "simp only [ProvenARM64.lower, ForallL]\n    exact ⟨" + ",\n      ".join(
            "⟨" + ", ".join(r + "_sound" for r in rs) + ", trivial⟩" for _, rs in xs) + ", trivial⟩"

    imports = "\n".join("import " + m for m in mods)
    OUT_PROOF.write_text(f"""-- Generated by scripts/arm64-proven.py from the `r_ARM64_*_sound` theorems of GoFV/Proof/Low/Rules. Do not edit.
import GoFV.Proof.Low.RuleL
import GoFV.Rules.ProvenARM64
{imports}

/-!
# The proven `ARM64.rules` rule set is sound (issue #385)

`arm64_allSound`: every rule of `GoFV.Rules.ProvenARM64.lower` has its lowered obligation
(`ArmRuleSet.AllSound`), from the rule lemmas of `GoFV/Proof/Low/Rules/*`.
-/

namespace GoFV.Proof.Low

open GoFV.Rules GoFV.Proof.Rules GoFV.Proof.Low.Rules

set_option maxRecDepth 4096 in
/-- Every rule of `ProvenARM64.lower` is sound. -/
theorem arm64_allSound : ArmRuleSet.AllSound ProvenARM64.lower := by
  refine ⟨?_, ?_, rfl, rfl, rfl, rfl, rfl, rfl⟩
  · {proofs(values)}
  · {proofs(blocks)}

end GoFV.Proof.Low
""")
    print(f"{nv} value rules, {nb} block rules")


if __name__ == "__main__":
    main()
