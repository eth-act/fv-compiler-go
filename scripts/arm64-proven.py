#!/usr/bin/env python3
"""The proven-only `ARM64.rules` rule set (issue #385).

  scripts/arm64-proven.py      # rewrite GoFV/Rules/ProvenARM64.lean and
                               # GoFV/Proof/Low/ProvenARM64.lean from the
                               # `r_ARM64_*_sound` theorems of GoFV/Proof/Low/Rules/*.lean

A value rule is proven by a theorem `r_ARM64_<n>_sound : ArmRule.Checked r_ARM64_<n>`, a block
rule by `r_ARM64_<n>_sound : BlockRuleL.Sound r_ARM64_<n>`. A rule whose expressions call Go's
`b2i` (which Phase 1's rule denotation `evalE` names `bool2int`; `GoFV.Rules.Eval` evaluates both
alike) is proven in its normalised form by `r_ARM64_<n>_b2i_sound : ArmRule.Checked (b2iNorm
r_ARM64_<n>)`, and the rule set lists `b2iNorm r_ARM64_<n>` (`b2iNorm` is emitted into the rule
set module). A rule whose result reads `b.Op` and `flagArg(b)` of a bound value `b` is proven in
its split form by `r_ARM64_<n>_flag_sound : ForallL ArmRule.Checked (flagSplit r_ARM64_<n>)`
(`GoFV.Rules.Derive.flagSplit`: one rule per condition op), and the rule set lists the rules of
`flagSplit r_ARM64_<n>` in its place; likewise a rule whose result reads `arm64Invert(cc)` of
its `CCop` auxint by `r_ARM64_<n>_cc_sound : ForallL ArmRule.Checked (ccSplit r_ARM64_<n>)`
(`GoFV.Rules.Derive.ccSplit`: one rule per integer condition op). The rule set keeps the generated
matching order (`GoFV.Rules.Generated.ARM64.ruleSet`: ops by Go name, rules per op as rulegen
tries them; block kinds likewise) restricted to the proven rules.
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
GEN = ROOT / "GoFV/Rules/Generated/ARM64.lean"
GEN_DIR = ROOT / "GoFV/Rules/Generated/ARM64"
LEMMAS = ROOT / "GoFV/Proof/Low/Rules"
OUT_SET = ROOT / "GoFV/Rules/ProvenARM64.lean"
OUT_PROOF = ROOT / "GoFV/Proof/Low/ProvenARM64.lean"


def proven():
    vals, blocks, norm, split, mods = set(), set(), set(), {}, []
    pat = re.compile(r"^theorem (r_ARM64_\w+)_sound : (ArmRule\.Checked|BlockRuleL\.Sound) ", re.M)
    npat = re.compile(r"^theorem (r_ARM64_\w+)_b2i_sound : ArmRule\.Checked \(b2iNorm (r_ARM64_\w+)\)",
                      re.M)
    spat = re.compile(r"^theorem (r_ARM64_\w+)_(flag|cc)_sound : ForallL ArmRule\.Checked "
                      r"\((flagSplit|ccSplit) (r_ARM64_\w+)\)", re.M)
    for f in sorted(LEMMAS.glob("*.lean")):
        text = f.read_text()
        found = pat.findall(text)
        nfound = npat.findall(text)
        sfound = spat.findall(text)
        if found or nfound or sfound:
            mods.append("GoFV.Proof.Low.Rules." + f.stem)
        for name, kind in found:
            (vals if kind == "ArmRule.Checked" else blocks).add(name)
        for name, r in nfound:
            assert name == r, (name, r)
            norm.add(name)
        for name, kind, fn, r in sfound:
            assert name == r and fn == kind + "Split", (name, kind, fn, r)
            split[name] = kind
    return vals, blocks, norm, split, mods


def lists(kind):
    """`ops_X`/`blocks_K` definitions of the generated modules: name -> rule names."""
    out = {}
    pat = re.compile(r"^def (%s_\w+) : List \w+ := \[(.*)\]$" % kind, re.M)
    for f in sorted(GEN_DIR.glob("*.lean")):
        for name, body in pat.findall(f.read_text()):
            out[name] = [x.strip() for x in body.split(",") if x.strip()]
    return out


def order():
    text = GEN.read_text()
    vals = re.findall(r"\(\.(\w+), (ops_\w+)\)", text)
    blocks = re.findall(r"\(\.(\w+), (blocks_\w+)\)", text)
    return vals, blocks


def main():
    pv, pb, pn, pf, mods = proven()
    ops, bls = lists("ops"), lists("blocks")
    vord, bord = order()
    values = [(op, [r for r in ops[l] if r in pv or r in pn or r in pf]) for op, l in vord]
    values = [(op, rs) for op, rs in values if rs]
    blocks = [(k, [r for r in bls[l] if r in pb]) for k, l in bord]
    blocks = [(k, rs) for k, rs in blocks if rs]
    nv = sum(len(rs) for _, rs in values)
    assert not ((pn | set(pf)) - {r for _, rs in values for r in rs}), (pn, pf)
    nb = sum(len(rs) for _, rs in blocks)
    q = "Generated.ARM64."

    def ref(r):
        return "b2iNorm " + q + r if r in pn else q + r

    def segments(rs):
        """Runs of rules listed as such, and the split rules (`flagSplit`, `ccSplit`), in order."""
        out = []
        for r in rs:
            if r in pf:
                out.append((pf[r], r))
            elif out and out[-1][0] == "plain":
                out[-1][1].append(r)
            else:
                out.append(("plain", [r]))
        return out

    def listExpr(rs):
        return " ++ ".join(
            "Derive.%sSplit " % kind + q + x if kind != "plain"
            else "[%s]" % ", ".join(ref(r) for r in x)
            for kind, x in segments(rs))

    def entries(xs):
        if not xs:
            return "[]"
        return "[" + ",\n    ".join("(.%s, %s)" % (k, listExpr(rs)) for k, rs in xs) + "]"

    OUT_SET.write_text(f"""-- Generated by scripts/arm64-proven.py from the `r_ARM64_*_sound` theorems of GoFV/Proof/Low/Rules. Do not edit.
import GoFV.Rules.Generated.ARM64
import GoFV.Rules.Derive

/-!
# The proven-only `ARM64.rules` rule set (issue #385)

`ARM64.rules` restricted to the rules with a merged lowered obligation (`ArmRule.Sound`,
`ArmRule.SetOp`, `ArmRule.Rename`, `BlockRuleL.Sound`; `GoFV/Proof/Low/ProvenARM64.lean`), in
matching order: the rule set of the checked `lower` (`GoFV.Opt.lowerChecked`). A rule on a
condition's op and flags (`flagArg`) is listed split by the condition op
(`GoFV.Rules.Derive.flagSplit`), which rewrites the same instances; a rule on `arm64Invert` of
its `CCop` auxint is listed split by the integer condition ops (`GoFV.Rules.Derive.ccSplit`).
-/

namespace GoFV.Rules.ProvenARM64

open GoFV.Rules

mutual
/-- `e` with Go's `b2i` calls named `bool2int`, as Phase 1's rule denotation (`evalE`) knows them
(`GoFV.Rules.Eval` evaluates both alike). -/
def Expr.b2iNorm : Expr → Expr
  | .field x n t => .field (Expr.b2iNorm x) n t
  | .call f as t => .call (if f == "b2i" then "bool2int" else f) (Expr.b2iNorms as) t
  | .method x n as t => .method (Expr.b2iNorm x) n (Expr.b2iNorms as) t
  | .builtin f as t => .builtin f (Expr.b2iNorms as) t
  | .conv t x => .conv t (Expr.b2iNorm x)
  | .assert t x => .assert t (Expr.b2iNorm x)
  | .unop o x t => .unop o (Expr.b2iNorm x) t
  | .binop o x y t => .binop o (Expr.b2iNorm x) (Expr.b2iNorm y) t
  | .index x i t => .index (Expr.b2iNorm x) (Expr.b2iNorm i) t
  | .deref x t => .deref (Expr.b2iNorm x) t
  | e => e
/-- `Expr.b2iNorm` of each expression. -/
def Expr.b2iNorms : List Expr → List Expr
  | [] => []
  | e :: es => Expr.b2iNorm e :: Expr.b2iNorms es
end

/-- `Expr.b2iNorm` of a result node's expressions. -/
def RNode.b2iNorm (n : RNode) : RNode where
  op := n.op
  ty := n.ty.map Expr.b2iNorm
  auxInt := n.auxInt.map Expr.b2iNorm
  aux := n.aux.map Expr.b2iNorm
  args := n.args.map fun
    | .expr e => .expr (Expr.b2iNorm e)
    | a => a

/-- A rule with Go's `b2i` calls of its condition and result named `bool2int`. -/
def b2iNorm (r : Rule) : Rule where
  loc := r.loc
  op := r.op
  vars := r.vars
  pat := r.pat
  cond := r.cond.map Expr.b2iNorm
  block := r.block
  result := match r.result with
    | .copy e => .copy (Expr.b2iNorm e)
    | .build ns => .build (ns.map RNode.b2iNorm)
    | res => res
  pos := r.pos

/-- `ARM64.rules` restricted to its {nv} proven value rules and {nb} proven block rules. -/
def lower : RuleSet where
  name := "ARM64"
  values := {entries(values)}
  blocks := {entries(blocks)}

end GoFV.Rules.ProvenARM64
""")

    def segProof(kind, x):
        if kind != "plain":
            return x + "_" + kind + "_sound"
        return "⟨" + ", ".join(r + ("_b2i_sound" if r in pn else "_sound") for r in x) + ", trivial⟩"

    def opProof(rs):
        segs = segments(rs)
        if len(segs) == 1:
            return segProof(*segs[0])
        return "⟨" + ", ".join(segProof(k, x) for k, x in segs) + "⟩"

    def proofs(xs):
        if not xs:
            return "exact trivial"
        return "simp only [ProvenARM64.lower, ForallL, ForallL.append_iff]\n    exact ⟨" + \
            ",\n      ".join(opProof(rs) for _, rs in xs) + ", trivial⟩"

    imports = "\n".join("import " + m for m in mods)
    OUT_PROOF.write_text(f"""-- Generated by scripts/arm64-proven.py from the `r_ARM64_*_sound` theorems of GoFV/Proof/Low/Rules. Do not edit.
import GoFV.Proof.Low.RuleL
import GoFV.Rules.ProvenARM64
{imports}

/-!
# The proven `ARM64.rules` rule set is sound (issue #385)

`arm64_allSound`: every rule of `GoFV.Rules.ProvenARM64.lower` has its lowered obligation
(`ArmRuleSet.AllSound`), from the rule lemmas of `GoFV/Proof/Low/Rules/*`.
-/

namespace GoFV.Proof.Low

open GoFV.Rules GoFV.Proof.Rules GoFV.Proof.Low.Rules

set_option maxRecDepth 4096 in
/-- Every rule of `ProvenARM64.lower` is sound. -/
theorem arm64_allSound : ArmRuleSet.AllSound ProvenARM64.lower := by
  refine ⟨?_, ?_, rfl, rfl, rfl, rfl, rfl, rfl⟩
  · {proofs(values)}
  · {proofs(blocks)}

end GoFV.Proof.Low
""")
    print(f"{nv} value rules, {nb} block rules")


if __name__ == "__main__":
    main()
