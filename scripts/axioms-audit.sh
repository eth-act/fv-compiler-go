#!/usr/bin/env bash
# Axioms audit of every theorem under GoFV.Proof (docs/GATE.md, docs/PLAN.md §0): for every
# module GoFV/Proof/**/*.lean (built first: `lake build`), one `lean` process imports the module
# and runs Lean's `collectAxioms` (what `#print axioms` prints) on every theorem the module
# declares, auxiliary theorems included. The modules are audited one by one because they need
# not import together (two of them may declare the same name). Allowed: propext,
# Classical.choice, Quot.sound, and the `_native` axioms that bv_decide/native_decide generate
# when they are listed by exact name in scripts/axioms-allowlist.txt. Anything else (sorryAx, a
# declared axiom, an unlisted _native axiom) is a violation.
#
# usage: scripts/axioms-audit.sh [--out DIR] [-j N]   (default tmp/axioms-audit, 4 processes)
# Writes DIR/<module>.lean and .out, DIR/axioms.txt (one line "<theorem> <axiom>" per
# non-standard axiom) and DIR/summary.txt; prints the summary. Exit 1 on a violation or when a
# module's audit fails.
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
out=$root/tmp/axioms-audit
jobs=4
while [ $# -gt 0 ]; do
  case $1 in
    --out) out=$2; shift 2 ;;
    -j) jobs=$2; shift 2 ;;
    *) echo "usage: $0 [--out DIR] [-j N]" >&2; exit 2 ;;
  esac
done
cd "$root"
rm -rf "$out"
mkdir -p "$out"
mods=$(find GoFV/Proof -name '*.lean' | sort | sed 's|\.lean$||; s|/|.|g')
[ -n "$mods" ] || { echo "axioms-audit: no GoFV/Proof modules" >&2; exit 1; }
for m in $mods; do
  cat >"$out/$m.lean" <<EOF
-- generated by scripts/axioms-audit.sh
import Lean
import $m
open Lean Elab Command

#eval show CommandElabM Unit from do
  let env ← getEnv
  let std : List Name := [\`\`propext, \`\`Classical.choice, \`\`Quot.sound]
  let some idx := env.getModuleIdx? \`$m | throwError "module not found"
  let thms := env.constants.map₁.fold (init := #[]) fun acc n ci =>
    match ci with
    | .thmInfo _ => if env.getModuleIdxFor? n == some idx then acc.push n else acc
    | _ => acc
  for t in thms.qsort Name.lt do
    for a in ← collectAxioms t do
      if !std.contains a then IO.println s!"AXIOM {t} {a}"
  IO.println s!"THEOREMS {thms.size}"
EOF
done
# One memcap scope for all the lean processes.
export out
status=0
echo "$mods" | scripts/memcap.sh xargs -P "$jobs" -I{} sh -c \
  'lake env lean "$out/{}.lean" >"$out/{}.out" 2>&1 || echo "exit $?" >>"$out/{}.out"' || status=$?
failed=()
n=0
for m in $mods; do
  k=$(sed -n 's/^THEOREMS //p' "$out/$m.out")
  if [ -z "$k" ] || grep -q '^exit ' "$out/$m.out"; then failed+=("$m"); else n=$((n + k)); fi
  sed -n 's/^AXIOM //p' "$out/$m.out"
done >"$out/axioms.txt"
allow=$(sed 's/#.*//; s/[[:space:]]*$//; /^$/d' scripts/axioms-allowlist.txt)
bad=$(awk -v allow="$allow" '
  BEGIN { k = split(allow, a, "\n"); for (i = 1; i <= k; i++) ok[a[i]] = 1 }
  !($2 in ok)' "$out/axioms.txt")
nnative=$(awk '$2 ~ /\._native\./ { print $1 }' "$out/axioms.txt" | sort -u | wc -l)
{
  echo "theorems audited: $n (modules: $(echo "$mods" | wc -l))"
  echo "theorems using a _native axiom (bv_decide/native_decide): $nnative"
  if [ ${#failed[@]} -gt 0 ] || [ "$status" != 0 ]; then
    echo "modules whose audit failed: ${#failed[@]} (xargs exit $status)"
    for m in "${failed[@]}"; do
      echo "  - $m: $(grep -m1 -E 'error|exit ' "$out/$m.out" | cut -c1-200)"
    done
  fi
  if [ -n "$bad" ]; then
    echo "violations: $(echo "$bad" | wc -l)"
    echo "$bad" | head -n 50 | sed 's/^/  - /'
  else
    echo "violations: 0"
  fi
} | tee "$out/summary.txt"
[ -z "$bad" ] && [ ${#failed[@]} -eq 0 ] && [ "$status" = 0 ]
