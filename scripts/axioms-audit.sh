#!/usr/bin/env bash
# Axioms audit of every theorem under GoFV.Proof (docs/GATE.md, docs/PLAN.md §0): one `lean`
# process imports every module GoFV/Proof/**/*.lean (built first: `lake build`; they import
# together, see GoFVTest/Proof/AllProof.lean) and runs Lean's `collectAxioms` (what
# `#print axioms` prints) on every theorem those modules declare, auxiliary theorems included.
# Allowed: propext, Classical.choice, Quot.sound, and the `_native` axioms that
# bv_decide/native_decide generate when they are listed by exact name in
# scripts/axioms-allowlist.txt. Anything else (sorryAx, a declared axiom, an unlisted _native
# axiom) is a violation.
#
# usage: scripts/axioms-audit.sh [--out DIR]   (default tmp/axioms-audit)
# Writes DIR/audit.lean and audit.out, DIR/axioms.txt (one line "<theorem> <axiom>" per
# non-standard axiom) and DIR/summary.txt; prints the summary. Exit 1 on a violation or when the
# audit fails.
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
out=$root/tmp/axioms-audit
while [ $# -gt 0 ]; do
  case $1 in
    --out) out=$2; shift 2 ;;
    *) echo "usage: $0 [--out DIR]" >&2; exit 2 ;;
  esac
done
cd "$root"
rm -rf "$out"
mkdir -p "$out"
mods=$(find GoFV/Proof -name '*.lean' | LC_ALL=C sort | sed 's|\.lean$||; s|/|.|g')
[ -n "$mods" ] || { echo "axioms-audit: no GoFV/Proof modules" >&2; exit 1; }
{
  echo "-- generated by scripts/axioms-audit.sh"
  echo "import Lean"
  echo "$mods" | sed 's/^/import /'
  cat <<'EOF'
open Lean Elab Command

#eval show CommandElabM Unit from do
  let env ← getEnv
  let std : List Name := [``propext, ``Classical.choice, ``Quot.sound]
  let mods : Array String := #[
EOF
  echo "$mods" | sed 's/.*/    "&",/; $s/,$//'
  cat <<'EOF'
  ]
  let mut idx : Std.HashMap Nat String := {}
  for m in mods do
    let some i := env.getModuleIdx? m.toName | throwError "module {m} not found"
    idx := idx.insert i.toNat m
  let thms := env.constants.map₁.fold (init := #[]) fun acc n ci =>
    match ci, env.getModuleIdxFor? n with
    | .thmInfo _, some i => if idx.contains i.toNat then acc.push n else acc
    | _, _ => acc
  for t in thms.qsort Name.lt do
    for a in ← collectAxioms t do
      if !std.contains a then IO.println s!"AXIOM {t} {a}"
  IO.println s!"THEOREMS {thms.size}"
EOF
} >"$out/audit.lean"
status=0
scripts/memcap.sh lake env lean "$out/audit.lean" >"$out/audit.out" 2>&1 || status=$?
sed -n 's/^AXIOM //p' "$out/audit.out" >"$out/axioms.txt"
n=$(sed -n 's/^THEOREMS //p' "$out/audit.out")
allow=$(sed 's/#.*//; s/[[:space:]]*$//; /^$/d' scripts/axioms-allowlist.txt)
bad=$(awk -v allow="$allow" '
  BEGIN { k = split(allow, a, "\n"); for (i = 1; i <= k; i++) ok[a[i]] = 1 }
  !($2 in ok)' "$out/axioms.txt")
nnative=$(awk '$2 ~ /\._native\./ { print $1 }' "$out/axioms.txt" | sort -u | wc -l)
{
  echo "theorems audited: ${n:-0} (modules: $(echo "$mods" | wc -l))"
  echo "theorems using a _native axiom (bv_decide/native_decide): $nnative"
  if [ -z "$n" ] || [ "$status" != 0 ]; then
    echo "audit failed (lean exit $status):"
    grep -m5 -E 'error' "$out/audit.out" | cut -c1-300 | sed 's/^/  - /'
  fi
  if [ -n "$bad" ]; then
    echo "violations: $(echo "$bad" | wc -l)"
    echo "$bad" | head -n 50 | sed 's/^/  - /'
  else
    echo "violations: 0"
  fi
} | tee "$out/summary.txt"
[ -z "$bad" ] && [ -n "$n" ] && [ "$status" = 0 ]
