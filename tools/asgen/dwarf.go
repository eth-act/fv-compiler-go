package main

import (
	"bytes"
	"fmt"
	"log"
	"strings"
)

// dwarfFiles are the files of cmd/internal/dwarf whose constants Const.lean carries.
var dwarfFiles = []string{"dwarf_defs.go", "dwarf.go"}

// dwarfFamilies are the name prefixes of the emitted constants: what the DIE writer
// (GoFV/Dwarf/Die.lean) and the line program (GoFV/Dwarf/Lines.lean) use.
var dwarfFamilies = []string{
	"DW_TAG_", "DW_AT_", "DW_FORM_", "DW_CLS_", "DW_OP_", "DW_LLE_", "DW_RLE_", "DW_INL_",
	"DW_LNS_", "DW_LNE_", "DW_ABRV_",
}

// dwarfWitnesses are spot values Lean checks (expected values from the Go declarations).
var dwarfWitnesses = []struct{ name, val string }{
	{"DW_TAG_formal_parameter", "5"}, {"DW_TAG_variable", "52"}, {"DW_AT_go_closure_offset", "10503"},
	{"DW_FORM_addr", "1"}, {"DW_FORM_addrx", "27"}, {"DW_FORM_udata_pseudo", "153"},
	{"DW_CLS_ADDRESS", "1"}, {"DW_CLS_GO_TYPEREF", "9"}, {"DW_OP_call_frame_cfa", "156"},
	{"DW_OP_fbreg", "145"}, {"DW_LLE_offset_pair", "4"}, {"DW_RLE_base_addressx", "1"},
	{"DW_INL_inlined", "1"}, {"DW_LNS_copy", "1"}, {"DW_LNE_set_address", "2"},
	{"DW_ABRV_FUNCTION", "3"}, {"DW_ABRV_INLINED_SUBROUTINE_RANGES", "9"},
	{"DW_ABRV_DICT_INDEX", "32"}, {"DW_ABRV_PUTVAR_START", "33"},
}

func dwarfFamily(n string) bool {
	for _, p := range dwarfFamilies {
		if strings.HasPrefix(n, p) {
			return true
		}
	}
	return false
}

// genDwarf generates GoFV/Dwarf/Const.lean.
func genDwarf(l *loader, source string) []byte {
	const pkg = "cmd/internal/dwarf"
	names := map[string]bool{}
	var b bytes.Buffer
	p := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	p("-- Generated by tools/asgen (scripts/gen-asm.sh) from Go %s\n", source)
	p("-- src/cmd/internal/dwarf/{dwarf_defs.go,dwarf.go}, values by go/types. DO NOT EDIT.\n\n")
	p("/-! # `cmd/internal/dwarf` constants\n\n")
	p("The integer constants `%s*`,\n", strings.Join(dwarfFamilies[:6], "*`, `"))
	p("`%s*` of the `const` declarations of\n", strings.Join(dwarfFamilies[6:], "*`, `"))
	p("`cmd/internal/dwarf` `dwarf_defs.go` and `dwarf.go` (the source line is noted above each\n")
	p("declaration), Go names verbatim, values computed by `go/types` (`DW_ABRV_*` by `iota`). -/\n\n")
	p("namespace GoFV.Dwarf\n")
	for _, f := range dwarfFiles {
		blocks := l.constBlocks(pkg, f, func(_ []string, n string) bool { return dwarfFamily(n) })
		for _, block := range blocks {
			p("\n-- %s:%d\n", f, block[0].line)
			for _, c := range block {
				if names[c.name] {
					log.Fatalf("dwarf: duplicate constant %s", c.name)
				}
				names[c.name] = true
				if c.val.ExactString()[0] == '-' {
					log.Fatalf("dwarf: negative constant %s", c.name)
				}
				p("def %s : Nat := %s\n", leanName(c.name), c.val.ExactString())
			}
		}
	}
	p("\n/-! Spot values. -/\n\n")
	for _, w := range dwarfWitnesses {
		if !names[w.name] {
			log.Fatalf("dwarf: witness %s not emitted", w.name)
		}
		p("example : %s = %s := rfl\n", w.name, w.val)
	}
	p("\nend GoFV.Dwarf\n")
	return b.Bytes()
}
