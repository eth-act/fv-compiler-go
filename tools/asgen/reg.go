package main

import (
	"bytes"
	"fmt"
	"log"
)

// regFiles are the files of cmd/internal/obj/arm64 whose integer constants Reg.lean carries.
var regFiles = []string{"a.out.go", "sysRegEnc.go"}

// regWitnesses are spot values Lean checks against the generated definitions (expected
// values worked out by hand from the Go declarations, not by asgen).
var regWitnesses = []struct{ name, val string }{
	{"REG_R0", "8192"}, {"REG_F0", "8224"}, {"REG_V0", "8256"}, {"REG_RSP", "8383"},
	{"REGSP", "8383"}, {"REGZERO", "8223"}, {"REGTMP", "8219"}, {"REGG", "8220"},
	{"REGLINK", "8222"}, {"REG_ARNG", "9216"}, {"REG_LSL", "8704"}, {"REG_EXT", "12288"},
	{"REG_SPECIAL", "16384"}, {"ARNG_16B", "1"}, {"C_XPOST", "32"}, {"BIG", "2040"},
	{"SHIFT_LR", "4194304"},
}

// genReg generates Reg.lean: every integer constant of the const declarations of
// a.out.go and sysRegEnc.go except the opcode block (`AADC = obj.ABaseARM64 +
// obj.A_ARCHSPECIFIC + iota` …, which is As.lean). It returns the file and the emitted names.
func genReg(l *loader, source string) ([]byte, map[string]bool) {
	const pkg = "cmd/internal/obj/arm64"
	names := map[string]bool{}
	var b bytes.Buffer
	p := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	p("-- Generated by tools/asgen (scripts/gen-asm.sh) from Go %s\n", source)
	p("-- src/cmd/internal/obj/arm64/{a.out.go,sysRegEnc.go}, values by go/types. DO NOT EDIT.\n\n")
	p("/-! # arm64 register numbers and operand constants\n\n")
	p("Every integer constant of the `const` declarations of `cmd/internal/obj/arm64` files\n")
	p("`a.out.go` and `sysRegEnc.go` (the source line is noted above each declaration), Go names\n")
	p("verbatim, values computed by `go/types` (the portable bases `obj.RBaseARM64`,\n")
	p("`obj.SpecialOperandARM64Base`, … come from `cmd/internal/obj`). Registers are obj numbers\n")
	p("(`REG_R0 = obj.RBaseARM64`), `SPOP_*` are `SpecialOperand`s, `C_*` operand classes, `AC_*`\n")
	p("`AClass`es. Omitted: the opcode block (`AADC` …, `AB`, `ABL`), which is `GoFV.Asm.As`\n")
	p("(`As.goNum`), and the non-constant `ARM64DWARFRegisters` / `SystemReg` tables. -/\n\n")
	p("namespace GoFV.Asm.ARM64\n")
	for _, file := range regFiles {
		blocks := l.constBlocks(pkg, file, func(block []string, n string) bool {
			return block[0] != "AADC"
		})
		for _, block := range blocks {
			p("\n-- %s:%d\n", file, block[0].line)
			for _, c := range block {
				if names[c.name] {
					log.Fatalf("arm64: duplicate constant %s", c.name)
				}
				names[c.name] = true
				p("def %s : Int := %s\n", leanName(c.name), c.val.ExactString())
			}
		}
	}
	p("\n/-! Spot values. -/\n\n")
	for _, w := range regWitnesses {
		if !names[w.name] {
			log.Fatalf("arm64: witness %s not emitted", w.name)
		}
		p("example : %s = %s := rfl\n", w.name, w.val)
	}
	p("\nend GoFV.Asm.ARM64\n")
	return b.Bytes(), names
}
