package main

import (
	"bytes"
	"fmt"
	"log"
	"strings"
)

// abiFiles are the files of internal/abi (linux/arm64) whose integer constants Abi.lean
// carries, with a filter on the names (nil: all).
var abiFiles = []struct {
	file string
	keep func(string) bool
}{
	{"symtab.go", nil},
	{"bounds.go", nil},
	{"stack.go", nil},
	{"abi_arm64.go", nil},
	{"type.go", func(n string) bool { return strings.HasPrefix(n, "TraceArgs") }},
}

// abiWitnesses are spot values Lean checks (expected values from the Go declarations).
var abiWitnesses = []struct{ name, val string }{
	{"PCDATA_UnsafePoint", "0"}, {"PCDATA_StackMapIndex", "1"}, {"PCDATA_PanicBounds", "4"},
	{"FUNCDATA_ArgsPointerMaps", "0"}, {"FUNCDATA_WrapInfo", "7"}, {"UnsafePointSafe", "-1"},
	{"UnsafePointRestartAtEntry", "-5"}, {"BoundsConvert", "8"}, {"numBoundsCodes", "9"},
	{"BoundsMaxReg", "15"}, {"BoundsMaxConst", "31"}, {"TraceArgsMaxLen", "171"},
	{"TraceArgsEndSeq", "255"}, {"ArgsSizeUnknown", "-2147483648"}, {"MINFUNC", "16"},
	{"IntArgRegs", "16"}, {"StackSmall", "128"},
}

// genAbi generates Abi.lean.
func genAbi(l *loader, source string) []byte {
	const pkg = "internal/abi"
	names := map[string]bool{}
	var b bytes.Buffer
	p := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	p("-- Generated by tools/asgen (scripts/gen-asm.sh) from Go %s\n", source)
	p("-- src/internal/abi/{symtab.go,bounds.go,stack.go,abi_arm64.go,type.go}, values by go/types. DO NOT EDIT.\n\n")
	p("/-! # `internal/abi` constants\n\n")
	p("The integer constants of the `const` declarations of `internal/abi` (linux/arm64) files\n")
	p("`symtab.go` (`PCDATA_*`, `FUNCDATA_*`, `UnsafePoint*`, `FuncFlag*`, `FuncID*`, …), `bounds.go`\n")
	p("(`BoundsErrorCode`s, `numBoundsCodes`, `BoundsMaxReg`, `BoundsMaxConst`), `stack.go`,\n")
	p("`abi_arm64.go` and the `TraceArgs*` constants of `type.go` (the source line is noted above\n")
	p("each declaration), Go names verbatim, values computed by `go/types`. -/\n\n")
	p("namespace GoFV.Asm.Abi\n")
	for _, f := range abiFiles {
		blocks := l.constBlocks(pkg, f.file, func(_ []string, n string) bool {
			return f.keep == nil || f.keep(n)
		})
		for _, block := range blocks {
			p("\n-- %s:%d\n", f.file, block[0].line)
			for _, c := range block {
				if names[c.name] {
					log.Fatalf("abi: duplicate constant %s", c.name)
				}
				names[c.name] = true
				p("def %s : Int := %s\n", leanName(c.name), c.val.ExactString())
			}
		}
	}
	p("\n/-! Spot values. -/\n\n")
	for _, w := range abiWitnesses {
		if !names[w.name] {
			log.Fatalf("abi: witness %s not emitted", w.name)
		}
		p("example : %s = %s := rfl\n", w.name, w.val)
	}
	p("\nend GoFV.Asm.Abi\n")
	return b.Bytes()
}
