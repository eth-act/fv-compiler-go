#!/usr/bin/env bash
# Generate GoFVTest/Proof/AllProof.lean: one module that imports every GoFV/Proof module
# (tracked, or untracked and not ignored), so a name declared by two proof modules fails its
# build (issue #133). The nightly gate checks that it is current and builds it (docs/GATE.md).
#
# usage: scripts/gen-allproof.sh           rewrite the file
#        scripts/gen-allproof.sh --check   exit 1 if the file is out of date
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
cd "$root"
out=GoFVTest/Proof/AllProof.lean
gen() {
  echo "-- generated by scripts/gen-allproof.sh; do not edit"
  echo "-- Every GoFV/Proof module; building this checks that they import together."
  git ls-files -co --exclude-standard 'GoFV/Proof/*.lean' | LC_ALL=C sort -u |
    sed 's|\.lean$||; s|/|.|g; s|^|import |'
}
case ${1:-} in
  --check)
    if ! gen | cmp -s - "$out"; then
      echo "gen-allproof: $out is out of date; run scripts/gen-allproof.sh" >&2
      exit 1
    fi ;;
  '') gen >"$out" ;;
  *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac
